"""Latih MLP, kuantisasi INT8, ekspor .tflite + C header, evaluasi.

Jalankan dari folder ml/:  python src/train.py
"""
import json

import numpy as np
import tensorflow as tf

from config import (FEATURES, MAE_TOLERANCE_PCT, MAX_INFERENCE_MS, MODELS_DIR,
                    PUMP_MAX_SEC, SEED)
from data import make_splits


def build_model() -> tf.keras.Model:
    model = tf.keras.Sequential([
        tf.keras.layers.Input(shape=(len(FEATURES),)),
        tf.keras.layers.Dense(16, activation="relu"),
        tf.keras.layers.Dense(8, activation="relu"),
        tf.keras.layers.Dense(1, activation="sigmoid"),  # output [0,1] x PUMP_MAX_SEC
    ])
    model.compile(optimizer="adam", loss="mse", metrics=["mae"])
    return model


def to_int8_tflite(model: tf.keras.Model, calib_x: np.ndarray) -> bytes:
    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]

    def rep():
        for row in calib_x[:200]:
            yield [row.reshape(1, -1).astype(np.float32)]

    conv.representative_dataset = rep
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    return conv.convert()


def write_c_header(data: bytes, path, var="g_agriedge_model"):
    with open(path, "w") as f:
        f.write("// AUTO-GENERATED by ml/src/train.py - JANGAN diedit manual\n#pragma once\n\n")
        f.write(f"alignas(16) const unsigned char {var}[] = {{\n")
        for i in range(0, len(data), 12):
            f.write("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]) + ",\n")
        f.write(f"}};\nconst unsigned int {var}_len = {len(data)};\n")


def predict_tflite(tflite_bytes: bytes, x: np.ndarray):
    """Jalankan model INT8 persis seperti di MCU. Return (pred_sec, latency_ms_rata2)."""
    import time
    it = tf.lite.Interpreter(model_content=tflite_bytes)
    it.allocate_tensors()
    i_d, o_d = it.get_input_details()[0], it.get_output_details()[0]
    i_s, i_z = i_d["quantization"]
    o_s, o_z = o_d["quantization"]
    out, lat = [], []
    for row in x:
        q = np.clip(np.round(row / i_s + i_z), -128, 127).astype(np.int8).reshape(1, -1)
        it.set_tensor(i_d["index"], q)
        t0 = time.perf_counter()
        it.invoke()
        lat.append((time.perf_counter() - t0) * 1000)
        y = (it.get_tensor(o_d["index"]).astype(np.float32)[0, 0] - o_z) * o_s
        out.append(y * PUMP_MAX_SEC)
    return np.array(out), float(np.mean(lat))


def main():
    tf.keras.utils.set_random_seed(SEED)
    MODELS_DIR.mkdir(exist_ok=True)
    s = make_splits()
    (xtr, ytr), (xva, yva), (xte, yte) = s["train"], s["val"], s["test"]

    model = build_model()
    model.fit(xtr, ytr / PUMP_MAX_SEC, validation_data=(xva, yva / PUMP_MAX_SEC),
              epochs=60, batch_size=32, verbose=2)

    blob = to_int8_tflite(model, xtr)
    (MODELS_DIR / "agriedge_int8.tflite").write_bytes(blob)
    write_c_header(blob, MODELS_DIR / "agriedge_model_data.h")

    pred, lat = predict_tflite(blob, xte)
    mae = float(np.mean(np.abs(pred - yte)))
    mae_pct = mae / PUMP_MAX_SEC * 100
    metrics = {
        "mae_sec": round(mae, 3),
        "mae_pct_of_max": round(mae_pct, 3),
        "model_size_kb": round(len(blob) / 1024, 3),
        "pc_latency_ms_avg": round(lat, 4),
        "pass_mae": mae_pct < MAE_TOLERANCE_PCT,
        "pass_latency_pc": lat < MAX_INFERENCE_MS,
        "note": "Latensi PC bukan latensi ESP32; ukur ulang di device.",
    }
    (MODELS_DIR / "metrics.json").write_text(json.dumps(metrics, indent=2))
    print(json.dumps(metrics, indent=2))


if __name__ == "__main__":
    main()
